using RetroBox.Core;

namespace RetroBox.Tests;

public sealed class RetroBoxHostHardwareTests : IDisposable
{
    private readonly string root = Path.Combine(Path.GetTempPath(), "retrobox-host-hardware-tests", Guid.NewGuid().ToString("N"));

    public RetroBoxHostHardwareTests()
    {
        Directory.CreateDirectory(root);
    }

    public void Dispose()
    {
        Directory.Delete(root, recursive: true);
    }

    [Fact]
    public void Optical_drive_is_the_installer_detected_device()
    {
        var device = Path.Combine(root, "usb-HL-DT-ST_DVDRAM-0:0");
        File.WriteAllText(device, string.Empty);
        var env = WriteEnv($"""
            # Physical hardware paths — generated by install-retropc.sh.
            CDROM_DEVICE={device}
            CDROM_STATUS=DETECTED
            """);

        Assert.Equal(device, RetroBoxHostHardware.ReadOpticalDrive(env));
    }

    [Fact]
    public void Optical_drive_is_absent_when_installer_found_none()
    {
        var device = Path.Combine(root, "sr0");
        File.WriteAllText(device, string.Empty);
        var env = WriteEnv($"CDROM_DEVICE={device}\nCDROM_STATUS=NOT_DETECTED\n");

        Assert.Null(RetroBoxHostHardware.ReadOpticalDrive(env));
    }

    [Fact]
    public void Optical_drive_is_absent_when_detected_device_is_gone()
    {
        var env = WriteEnv($"CDROM_DEVICE={Path.Combine(root, "unplugged")}\nCDROM_STATUS=DETECTED\n");

        Assert.Null(RetroBoxHostHardware.ReadOpticalDrive(env));
    }

    [Fact]
    public void Optical_drive_is_absent_without_status_or_file()
    {
        var device = Path.Combine(root, "sr0");
        File.WriteAllText(device, string.Empty);

        Assert.Null(RetroBoxHostHardware.ReadOpticalDrive(WriteEnv($"CDROM_DEVICE={device}\n")));
        Assert.Null(RetroBoxHostHardware.ReadOpticalDrive(Path.Combine(root, "missing.env")));
    }

    [Fact]
    public void Same_device_matches_itself_and_symlinks_to_it()
    {
        var device = Path.Combine(root, "sr0");
        File.WriteAllText(device, string.Empty);
        var byId = Path.Combine(root, "by-id");
        Directory.CreateDirectory(byId);
        var link = Path.Combine(byId, "ata-HL-DT-ST_DVDRAM");
        File.CreateSymbolicLink(link, Path.Combine("..", "sr0"));

        Assert.True(RetroBoxHostHardware.IsSameDevice(device, device));
        Assert.True(RetroBoxHostHardware.IsSameDevice(device, link));
        Assert.True(RetroBoxHostHardware.IsSameDevice(link, device));
    }

    [Fact]
    public void Different_devices_do_not_match()
    {
        var sr0 = Path.Combine(root, "sr0");
        var sr1 = Path.Combine(root, "sr1");
        File.WriteAllText(sr0, string.Empty);
        File.WriteAllText(sr1, string.Empty);

        Assert.False(RetroBoxHostHardware.IsSameDevice(sr0, sr1));
        Assert.False(RetroBoxHostHardware.IsSameDevice(sr0, Path.Combine(root, "missing")));
    }

    private string WriteEnv(string content)
    {
        var path = Path.Combine(root, "hardware.env");
        File.WriteAllText(path, content);
        return path;
    }
}
